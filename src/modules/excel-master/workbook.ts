export async function createWorkbook(
  data: ImportBundle = demoData,
  selectedSheets: readonly (typeof SHEETS)[number][] = defaultSheets(data),
): Promise<Uint8Array> {
  const workbook = new ExcelJS.Workbook();
  workbook.creator = "ERP VDA CA";
  const readme = workbook.addWorksheet("README");
  readme.addRow(["Client and Service Excel Import/Export"]);
  readme.addRow([
    "Fill the input sheets from row 6. Required headers are marked [required]. Hover the readable headers for help. ValidationReport and Rulebook are generated by the application.",
  ]);
  readme.getRow(1).font = { bold: true, size: 16 };
  readme.getRow(1).height = 30;
  readme.getRow(2).height = 30;
  readme.getColumn(1).width = 110;
  if (selectedSheets.includes("Clients"))
    workbook.definedNames.add("Clients!$A$6:$A$1000", "ClientKeys");
  if (selectedSheets.includes("Services"))
    workbook.definedNames.add("Services!$A$6:$A$1000", "ServiceKeys");
  selectedSheets.forEach((sheetName) => {
    const sheet = workbook.addWorksheet(sheetName);
    const columns = COLUMNS[sheetName].filter((column) => !hiddenByDefault(column.key));
    columns.forEach((column, index) => {
      const row = index + 1;
      sheet.mergeCells(1, row, 2, row);
      const cell = sheet.getCell(1, row);
      cell.value = column.header;
      sheet.getColumn(index + 1).width = Math.min(
        44,
        Math.max(16, Math.max(column.header.length, humanizeHeader(column.header).length) + 4),
      );
      sheet.getColumn(index + 1).hidden = hiddenByDefault(column.key);
    });
    sheet.mergeCells(3, 1, 3, columns.length);
    sheet.getCell(3, 1).value =
      `${sheetName}: enter one record per row starting at row 6. Hover a readable header for input guidance. Do not rename or reorder the technical headers.`;
    columns.forEach((column, index) => {
      const row = index + 1;
      sheet.mergeCells(4, row, 5, row);
      const cell = sheet.getCell(4, row);
      cell.value = humanizeHeader(column.header);
      cell.note = columnHelp(column);
    });
    for (let index = 1; index <= columns.length; index += 1) {
      const technicalHeader = sheet.getCell(1, index);
      technicalHeader.font = { bold: true, color: { argb: "7F1D1D" } };
      technicalHeader.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FEE2E2" } };
      technicalHeader.alignment = { horizontal: "center", vertical: "middle", wrapText: true };
    }
    sheet.getRow(1).height = 30;
    for (let index = 1; index <= columns.length; index += 1) {
      const readableHeader = sheet.getCell(4, index);
      readableHeader.font = { bold: true, color: { argb: "FFFFFF" } };
      readableHeader.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "334155" } };
      readableHeader.alignment = { horizontal: "center", vertical: "middle", wrapText: true };
    }
    sheet.getRow(4).height = 30;
    sheet.getRow(5).height = 30;
    sheet.getRow(2).font = { color: { argb: "7F1D1D" } };
    sheet.getRow(3).font = { color: { argb: "64748B" }, size: 10 };
    sheet.getRow(3).alignment = { wrapText: true };
    sheet.views = [{ state: "frozen", ySplit: 5 }];
    const rows = data[sheetMap[sheetName]];
    rows.forEach((row) => sheet.addRow(columns.map((column) => sanitizeCell(row[column.key]))));
    sheet.autoFilter = {
      from: "A4",
      to: `${columnLetter(columns.length)}${Math.max(5, rows.length + 5)}`,
    };
    columns.forEach((column, index) => {
      if (
        [
          "client_key",
          "location_key",
          "contact_key",
          "registration_key",
          "service_key",
          "task_key",
          "parent_task_key",
          "predecessor_task_key",
          "successor_task_key",
          "pan",
          "tan",
          "gstin",
          "cin",
          "llpin",
          "postal_code",
        ].includes(column.key)
      )
        sheet.getColumn(index + 1).numFmt = "@";
      if (column.enum)
        (sheet.getColumn(index + 1) as unknown as { dataValidation: unknown }).dataValidation = {
          type: "list",
          allowBlank: !column.required,
          formulae: [`"${column.enum.join(",")}"`],
          error: "Choose a value from the list.",
          errorTitle: "Invalid value",
          showErrorMessage: true,
        };
    });
    applyRelationshipRules(workbook, sheet, sheetName, columns, selectedSheets);
  });
  const report = workbook.addWorksheet("ValidationReport");
  report.addRow(["severity", "code", "sheet", "row", "column", "header", "value", "message"]);
  for (let index = 1; index <= 8; index += 1) {
    const header = report.getCell(1, index);
    header.font = { bold: true, color: { argb: "7F1D1D" } };
    header.fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FEE2E2" } };
  }
  report.getRow(1).height = 30;
  report.views = [{ state: "frozen", ySplit: 1 }];
  addRulebook(workbook, selectedSheets);
  return new Uint8Array((await workbook.xlsx.writeBuffer()) as unknown as ArrayBuffer);
}

function columnLetter(number: number): string {
  let result = "";
  let current = number;
  while (current > 0) {
    const remainder = (current - 1) % 26;
    result = String.fromCharCode(65 + remainder) + result;
    current = Math.floor((current - 1) / 26);
  }
  return result;
}

function defaultSheets(data: ImportBundle): (typeof SHEETS)[number][] {
  return SHEETS.filter(
    (sheet) => sheet === "Clients" || sheet === "Services" || data[sheetMap[sheet]].length > 0,
  );
}
function humanizeHeader(header: string): string {
  return header
    .replace(/\s*\[required\]\s*$/u, "")
    .split("_")
    .map((part) => (part ? part[0].toUpperCase() + part.slice(1) : part))
    .join(" ");
}

function columnHelp(column: {
  key: string;
  required?: boolean;
  type?: string;
  enum?: readonly string[];
}): string {
  const relationship = [
    "client_key",
    "service_key",
    "parent_task_key",
    "predecessor_task_key",
    "successor_task_key",
    "location_key",
    "registration_key",
    "contact_key",
  ].includes(column.key);
  const required = column.required
    ? "Required. "
    : "Optional. Leave blank when it does not apply. ";
  const type = column.enum
    ? `Choose one of: ${column.enum.join(", ")}. `
    : column.type === "boolean"
      ? "Enter true or false. "
      : column.type === "date"
        ? "Enter a valid date as YYYY-MM-DD. "
        : column.type === "number"
          ? "Enter a numeric value, not text. "
          : "Enter plain text. ";
  const relation = relationship
    ? "This key must match the related record in its parent sheet; Excel highlights missing relationships in red. "
    : "";
  return `${required}${type}${relation}The user enters this value.`;
}

