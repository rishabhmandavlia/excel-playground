function rulebookRules(sheet: string): string {
  if (sheet.startsWith("Client") && sheet !== "Clients")
    return "client_id/client_key must resolve to the stated client. IDs and keys must agree when both are present.";
  if (sheet.startsWith("Service") && sheet !== "Services")
    return "service_template_id/service_key must resolve to the stated service. Task parents and dependencies must remain within the same service and stay acyclic.";
  return "Keys are unique. Existing IDs are authoritative. IDs, revisions, and status controls support safe round-trip updates.";
}

function applyRelationshipRules(
  workbook: ExcelJS.Workbook,
  sheet: ExcelJS.Worksheet,
  sheetName: string,
  columns: readonly { key: string }[],
  selectedSheets: readonly string[],
): void {
  const indexOf = (key: string) => columns.findIndex((column) => column.key === key) + 1;
  const addReference = (key: string, rangeName: string, message: string) => {
    const index = indexOf(key);
    if (!index) return;
    const letter = columnLetter(index);
    for (let row = 6; row <= VALIDATION_ROW_LIMIT; row += 1)
      sheet.getCell(row, index).dataValidation = {
        type: "custom",
        allowBlank: true,
        formulae: [`=OR(${letter}${row}=\"\",COUNTIF(${rangeName},${letter}${row})>0)`],
        error: message,
        errorTitle: "Relationship not found",
        prompt: "Use a key from the related sheet.",
        promptTitle: "Reference key",
        showErrorMessage: true,
        showInputMessage: true,
      };
    sheet.addConditionalFormatting({
      ref: `${letter}6:${letter}${VALIDATION_ROW_LIMIT}`,
      rules: [
        {
          type: "expression",
          priority: 1,
          formulae: [`=AND(${letter}6<>\"\",COUNTIF(${rangeName},${letter}6)=0)`],
          style: {
            fill: { type: "pattern", pattern: "solid", fgColor: { argb: "FECACA" } },
            font: { color: { argb: "991B1B" } },
          },
        },
      ],
    });
  };
  if (
    ["ClientLocations", "ClientContacts", "ClientRegistrations"].includes(sheetName) &&
    selectedSheets.includes("Clients")
  )
    addReference("client_key", "ClientKeys", "Client key does not exist on the Clients sheet.");
  if (
    ["ServiceTasks", "ServiceDependencies"].includes(sheetName) &&
    selectedSheets.includes("Services")
  )
    addReference("service_key", "ServiceKeys", "Service key does not exist on the Services sheet.");
  if (sheetName === "ServiceTasks") {
    const parent = indexOf("parent_task_key");
    if (parent) {
      const key = columnLetter(parent);
      sheet.addConditionalFormatting({
        ref: `${key}6:${key}${VALIDATION_ROW_LIMIT}`,
        rules: [
          {
            type: "expression",
            priority: 2,
            formulae: [
              `=AND(${key}6<>\"\",COUNTIFS($A$6:$A$${VALIDATION_ROW_LIMIT},$A6,$B$6:$B$${VALIDATION_ROW_LIMIT},${key}6)=0)`,
            ],
            style: {
              fill: { type: "pattern", pattern: "solid", fgColor: { argb: "FECACA" } },
              font: { color: { argb: "991B1B" } },
            },
          },
        ],
      });
    }
  }
  if (sheetName === "ServiceDependencies") {
    const service = indexOf("service_key");
    const pre = indexOf("predecessor_task_key");
    const suc = indexOf("successor_task_key");
    if (service && pre && suc) {
      const s = columnLetter(service);
      for (const index of [pre, suc]) {
        const key = columnLetter(index);
        sheet.addConditionalFormatting({
          ref: `${key}6:${key}${VALIDATION_ROW_LIMIT}`,
          rules: [
            {
              type: "expression",
              priority: 3,
              formulae: [
                `=AND(${key}6<>\"\",COUNTIFS($A$6:$A$${VALIDATION_ROW_LIMIT},${s}6,$B$6:$B$${VALIDATION_ROW_LIMIT},${key}6)=0)`,
              ],
              style: {
                fill: { type: "pattern", pattern: "solid", fgColor: { argb: "FECACA" } },
                font: { color: { argb: "991B1B" } },
              },
            },
          ],
        });
      }
    }
  }
}

