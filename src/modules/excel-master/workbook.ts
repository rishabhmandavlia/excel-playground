export async function parseWorkbook(
  bytes: Uint8Array,
  expectedSheets?: readonly (typeof SHEETS)[number][],
): Promise<{ data: ImportBundle; issues: ValidationIssue[] }> {
  const workbook = new ExcelJS.Workbook();
  await workbook.xlsx.load(
    Buffer.from(bytes) as unknown as Parameters<typeof workbook.xlsx.load>[0],
  );
  const data = emptyData();
  const issues: ValidationIssue[] = [];
  const sheetsToParse =
    expectedSheets ?? SHEETS.filter((name) => Boolean(workbook.getWorksheet(name)));
  sheetsToParse.forEach((name) => {
    const sheet = workbook.getWorksheet(name);
    if (!sheet) {
      issues.push({
        severity: "ERROR",
        code: "INVALID_FORMAT",
        sheet: name,
        row: 1,
        column: 1,
        header: "",
        value: "",
        message: `Missing worksheet ${name}.`,
      });
      return;
    }
    const sourceColumns = COLUMNS[name];
    const headerRow = sheet.getRow(1);
    const headers = (headerRow.values as unknown[])
      .slice(1)
      .map((value: unknown) => String(value ?? "").trim());
    const seen = new Set<string>();
    headers.forEach((header, i) => {
      const key = header.replace(/\s*\[required\]\s*$/u, "").trim();
      if (seen.has(key))
        issues.push({
          severity: "ERROR",
          code: "DUPLICATE_COLUMN",
          sheet: name,
          row: 4,
          column: i + 1,
          header,
          value: header,
          message: "Column header is duplicated.",
        });
      seen.add(key);
      if (!sourceColumns.some((column) => column.header === header))
        issues.push({
          severity: "ERROR",
          code: "UNKNOWN_COLUMN",
          sheet: name,
          row: 4,
          column: i + 1,
          header,
          value: header,
          message: "Column is not part of the workbook contract.",
        });
    });
    const columnEntries = headers
      .map((header, index) => ({
        column: sourceColumns.find((candidate) => candidate.header === header),
        index,
      }))
      .filter((entry): entry is { column: (typeof sourceColumns)[number]; index: number } =>
        Boolean(entry.column),
      );
    const rows = data[sheetMap[name]];
    for (let rowNo = 6; rowNo <= sheet.rowCount; rowNo++) {
      const row = sheet.getRow(rowNo);
      if (
        (row.values as unknown[])
          .slice(1)
          .every(
            (value: unknown) =>
              value === null || value === undefined || String(value).trim() === "",
          )
      )
        continue;
      const item: Record<string, unknown> = {};
      columnEntries.forEach(({ column, index }) => {
        const cell = row.getCell(index + 1);
        if (cell.type === ExcelJS.ValueType.Formula)
          issues.push({
            severity: "ERROR",
            code: "INVALID_TYPE",
            sheet: name,
            row: rowNo,
            column: index + 1,
            header: column.header,
            value: cell.value,
            message: "Formulas are not accepted in input cells.",
          });
        item[column.key] = cell.type === ExcelJS.ValueType.Date ? cell.value : cell.value;
      });
      rows.push(item);
    }
  });
  const result = validateBundle(data);
  return { data: result.data, issues: [...issues, ...result.issues] };
}

export function validationReportRows(issues: readonly ValidationIssue[]): (string | number)[][] {
  return issues.map((issue) => [
    issue.severity,
    issue.code,
    issue.sheet,
    issue.row,
    issue.column,
    issue.header,
    String(issue.value ?? ""),
    issue.message,
  ]);
}
